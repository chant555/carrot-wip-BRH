"""Bound software extensions of a physical one-touch turn-signal request."""

ONE_TOUCH_MAX_FLASHES = 4
ONE_TOUCH_MAX_S = ONE_TOUCH_MAX_FLASHES * 0.8


class OneTouchBlinkerLimit:
  """Count lamp rising edges per press, with a deadline if lamp feedback stalls.

  Releasing the hold cannot cancel flashes generated by the vehicle itself.
  A latched lever is a sustained driver request and is not a one-touch request.
  Expiration remains latched until a fresh press/latch, not a lamp's dark phase.
  """

  def __init__(self):
    self.counts = None
    self.side = 0
    self.flashes = 0
    self.elapsed = 0.0
    self.lit = False
    self.expired = False

  def update(self, car, dt):
    counts = (getattr(car, "leftBlinkerStalkCount", None), getattr(car, "rightBlinkerStalkCount", None))
    lamp = getattr(car, "blinkerLamp", None)
    lever = getattr(car, "blinkerLever", None)
    if None in counts or lamp is None or lever is None:
      return  # Legacy cars without physical lever/lamp feedback retain their behavior.
    previous, self.counts = self.counts, counts
    press = 0
    if previous is not None:
      press = 1 if counts[0] != previous[0] else 2 if counts[1] != previous[1] else 0
    if not press and not self.side and lever == 1:
      press = lamp if lamp in (1, 2) else 1 if car.leftBlinker else 2 if car.rightBlinker else 0

    if lever == 2:
      self.side, self.expired = 0, False
      return
    if press:
      self.side, self.flashes, self.elapsed, self.lit, self.expired = press, 0, 0.0, False, False
    elif self.side:
      self.elapsed += dt
    if self.side:
      lit = lamp == self.side
      if lit and not self.lit:
        self.flashes += 1
      self.lit = lit
      # Release on the fourth lighting, before another off/on cycle can be extended.
      self.expired |= self.flashes >= ONE_TOUCH_MAX_FLASHES or self.elapsed >= ONE_TOUCH_MAX_S - 1e-9

  def allows(self, side):
    return not (self.expired and side == self.side)
